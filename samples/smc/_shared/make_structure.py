"""Generate the shared synthetic EUR/USD 1H structure series used by several SMC lessons.

Uptrend: low 1.0800 → HH 1.0850 → HL 1.0822 → HH 1.0890 → HL 1.0862 → HH 1.0925 → HL 1.0900 → sweep high 1.0930,
then a sharp drop (CHOCH below 1.0900) to 1.0868, a lower high at 1.0905 and a lower low at 1.0850 (bearish BOS).
"""

import csv
from pathlib import Path

from smckit import from_pivots

PIVOTS = [(0, 1.0830), (2, 1.0800), (6, 1.0850), (9, 1.0822), (14, 1.0890), (17, 1.0862), (22, 1.0925),
          (25, 1.0900), (27, 1.0930), (33, 1.0868), (36, 1.0905), (41, 1.0850)]
OUT = Path(__file__).with_name("eurusd_1h_structure.csv")

if __name__ == "__main__":
    candles = from_pivots(PIVOTS, seed=4, wick=0.0007, noise=0.0003)
    # the 1.0930 high is a sweep: it closes back under the 1.0925 high
    c27, c28 = candles[27], candles[28]
    candles[27] = type(c27)(c27.t, c27.label, c27.o, c27.h, c27.l, 1.0916)
    candles[28] = type(c28)(c28.t, c28.label, 1.0916, 1.0921, 1.0911, 1.0913)
    c29 = candles[29]
    candles[29] = type(c29)(c29.t, c29.label, 1.0913, max(c29.h, 1.0913), c29.l, c29.c)
    for c in candles:
        assert c.l <= min(c.o, c.c) <= max(c.o, c.c) <= c.h, c
    with OUT.open("w", newline="") as f:
        f.write("# SYNTHETIC DATA - educational illustration only. NOT historical EUR/USD quotes.\n")
        f.write("# Shared SMC structure series, generated by make_structure.py from swing pivots. 1-hour candles.\n")
        w = csv.writer(f)
        w.writerow(["i", "open", "high", "low", "close"])
        for c in candles:
            w.writerow([c.t, f"{c.o:.4f}", f"{c.h:.4f}", f"{c.l:.4f}", f"{c.c:.4f}"])
    print(OUT)
