"""
One full structure cycle: uptrend (HH/HL, bullish BOS), range, bearish CHOCH, downtrend (LH/LL, bearish BOS).

Candles: data/eurusd_4h_cycle.csv (synthetic, generated by make_data.py from the pivots below).
"""

from _paths import DATA, OUT
from chartkit import Candle, Chart, Reveal, save
from sdkit import load

NAME = "market-structure-cycle"
C = load(DATA / "eurusd_4h_cycle.csv", Candle, unit_label="4H candle")
N = len(C)
# (index, price, label, is_high)
PIVOTS = [(5, 1.0850, "H", True), (8, 1.0825, "HL", False), (13, 1.0880, "HH", True), (16, 1.0858, "HL", False),
          (21, 1.0910, "HH", True), (24, 1.0884, "HL", False), (28, 1.0908, "LH", True), (31, 1.0886, "HL", False),
          (35, 1.0906, "LH", True), (39, 1.0862, "LL", False), (42, 1.0878, "LH", True), (46, 1.0838, "LL", False),
          (49, 1.0856, "LH", True), (54, 1.0812, "LL", False)]
RANGE = (1.0884, 1.0910)
# (name, level, from pivot index, direction)
BREAKS = [("BOS", 1.0850, 5, +1), ("BOS", 1.0880, 13, +1), ("CHOCH", 1.0884, 31, -1), ("BOS", 1.0862, 39, -1),
          ("BOS", 1.0838, 46, -1)]


def first_close_beyond(level, start, d):
    return next(k for k in range(start + 1, N) if (C[k].c - level) * d > 0)


def validate():
    for c in C:
        assert c.l <= min(c.o, c.c) <= max(c.o, c.c) <= c.h
    for i, p, _, hi in PIVOTS:
        near = [C[j] for j in range(max(0, i - 2), min(N, i + 3)) if j != i]
        if hi:
            assert C[i].h == p and all(c.h < p for c in near), i
        else:
            assert C[i].l == p and all(c.l > p for c in near), i
    for name, lvl, s, d in BREAKS:
        k = first_close_beyond(lvl, s, d)
        assert all((C[j].c - lvl) * d <= 0 for j in range(s, k)), name
    assert all(RANGE[0] <= c.c <= RANGE[1] for c in C[22:36]), "range closes stay inside"


validate()


def build(t, reveal: Reveal | None = None):
    ch = Chart(t, reveal)
    phases = [("up", -0.5, 21.5, "Uptrend: HH + HL", t.bull), ("range", 21.5, 36.5, "Range", t.zone),
              ("down", 36.5, N - 0.5, "Downtrend: LH + LL", t.bear)]
    for g, a, b, name, col in phases:
        with ch.group(g):
            ch.zone(a, b, 1.0796, 1.0932, color=col, alpha=0.06)
            ch.label((a + b) / 2, 1.0930, f"<b>{name}</b>", size=12, color=t.ink2, xanchor="center", yanchor="top")
    with ch.group("range"):
        ch.zone(21.5, 36.5, *RANGE, color=t.zone, alpha=0.18)
    ch.candles(C, "EUR/USD 4H (synthetic)", price_fmt=".4f", x=list(range(N)), text=[c.label for c in C])
    for i, p, name, hi in PIVOTS:
        g = "up" if i <= 21 else "range" if i <= 35 else "down"
        with ch.group(g):
            ch.label(i, p + (0.0003 if hi else -0.0003), f"<b>{name}</b>", size=11,
                     color=t.bull_text if name in ("HH", "HL") else t.bear_text if name in ("LH", "LL") else t.ink2,
                     xanchor="center", yanchor="bottom" if hi else "top")
    for name, lvl, s, d in BREAKS:
        k = first_close_beyond(lvl, s, d)
        g = "chochg" if name == "CHOCH" else ("up" if d > 0 else "down")
        with ch.group(g):
            ch.hline(s, k + 0.4, lvl, color=t.accent if name == "CHOCH" else t.ink2, dash="dash",
                     width=1.8 if name == "CHOCH" else 1.2)
            ch.label((s + k) / 2, lvl + 0.00012 * d, f"<b>{name}</b>", size=10,
                     color=t.accent if name == "CHOCH" else t.ink2, xanchor="center",
                     yanchor="bottom" if d > 0 else "top")
    ch.header("Price Action · Market Structure", "Market Structure — One Full Cycle",
              "EUR/USD · 4-hour candles · uptrend → range → change of character → downtrend",
              key=[("■", t.bull, "HH / HL"), ("■", t.bear, "LH / LL"), ("━", t.accent, "CHOCH"),
                   ("┅", t.ink2, "BOS")])
    ch.footnote("Synthetic candles built from the swing points in the Market Structure lesson")
    ch.caption()
    ch.axes(x_range=[-0.8, N - 0.2], y_range=[1.0796, 1.0934], y_dtick=0.0020, y_fmt=".4f", x_title="4-hour candles",
            x_ticks=(list(range(0, N, 6)), [str(i + 1) for i in range(0, N, 6)]))
    return ch.fig


def main():
    paths = save(NAME, build, "Market Structure Cycle", OUT)
    print(NAME, [(n, l, first_close_beyond(l, s, d)) for n, l, s, d in BREAKS], ', '.join(p.name for p in paths))


if __name__ == "__main__":
    main()
