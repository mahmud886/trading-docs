"""
A trend from strong to exhausted: shallow pullbacks along a trendline, then a deep (80%) pullback that breaks the
trendline, a lower high, and a break of the last higher low.

Candles: data/gbpusd_4h_trend.csv (synthetic, generated by make_data.py from the pivots below).
"""

import plotly.graph_objects as go

from _paths import DATA, OUT
from chartkit import Candle, Chart, Reveal, save
from sdkit import load

NAME = "trend-strength-exhaustion"
C = load(DATA / "gbpusd_4h_trend.csv", Candle, unit_label="4H candle")
N = len(C)
PIV = {0: 1.2500, 6: 1.2580, 9: 1.2550, 15: 1.2650, 18: 1.2610, 24: 1.2720, 29: 1.2632, 34: 1.2705, 39: 1.2600}
LEGS = [(0, 6, 9), (9, 15, 18), (18, 24, 29)]  # (impulse start low, high, pullback low)
TL = (9, 18)  # trendline through these two higher lows
EMA_N = 20


def depth(a, h, b):
    return (PIV[h] - PIV[b]) / (PIV[h] - PIV[a])


def tl_at(x):
    (x0, x1) = TL
    return PIV[x0] + (PIV[x1] - PIV[x0]) * (x - x0) / (x1 - x0)


def ema(values, n):
    k, out = 2 / (n + 1), []
    for v in values:
        out.append(v if not out else out[-1] + k * (v - out[-1]))
    return out


EMA = ema([c.c for c in C], EMA_N)


def first_close_below(level, start):
    return next(k for k in range(start + 1, N) if C[k].c < level)


def validate():
    for c in C:
        assert c.l <= min(c.o, c.c) <= max(c.o, c.c) <= c.h
    for i, p in PIV.items():
        if i == 0:
            continue
        near = [C[j] for j in range(max(0, i - 2), min(N, i + 3)) if j != i]
        hi = i in (6, 15, 24, 34)
        assert (C[i].h == p and all(c.h < p for c in near)) if hi else (C[i].l == p and all(c.l > p for c in near)), i
    d = [round(depth(*leg) * 100) for leg in LEGS]
    assert d[0] < 50 and d[1] < 50 and d[2] >= 78, d
    assert all(C[k].l >= tl_at(k) - 0.0004 for k in range(TL[0], 26)), "trendline holds through the strong phase"
    assert C[29].l < tl_at(29) - 0.0020, "the deep pullback breaks the trendline"
    assert PIV[34] < PIV[24], "lower high"
    k = first_close_below(PIV[29], 34)
    assert all(c.c >= PIV[29] for c in C[29:k]), "first close below the last higher low"


validate()


def build(t, reveal: Reveal | None = None):
    ch = Chart(t, reveal)
    n_vis = len(ch.reveal.visible(C))
    with ch.group("ema"):
        if ch.reveal.alpha("ema") > 0:
            ch.fig.add_trace(go.Scatter(x=list(range(n_vis)), y=EMA[:n_vis], mode="lines", showlegend=False,
                                        line=dict(color=t.zone, width=1.6), opacity=ch.reveal.alpha("ema"),
                                        hoverinfo="skip"))
    with ch.group("tl"):
        ch.fig.add_shape(type="line", x0=TL[0], y0=tl_at(TL[0]), x1=31, y1=tl_at(31),
                         line=dict(color=t.ink2, width=1.6), opacity=ch.reveal.alpha("tl"))
        ch.label(31, tl_at(31) + 0.0003, "trendline", size=11, color=t.ink2, xanchor="right", yanchor="bottom")
    ch.candles(C, "GBP/USD 4H (synthetic)", price_fmt=".4f", x=list(range(N)), text=[c.label for c in C])
    names = ("strong", "strong", "exhaust")
    for k, (a, h, b) in enumerate(LEGS):
        with ch.group(names[k] if k < 2 else "exhaust"):
            pct = depth(a, h, b) * 100
            ch.label(b, PIV[b] - 0.0004, f"<b>pullback {pct:.0f}%</b>", size=11,
                     color=t.bull_text if pct < 50 else t.bear_text, xanchor="center", yanchor="top")
    with ch.group("strong"):
        for i in (6, 15, 24):
            ch.label(i, PIV[i] + 0.0004, "<b>HH</b>", size=11, color=t.bull_text, xanchor="center", yanchor="bottom")
    with ch.group("exhaust"):
        ch.label(34, PIV[34] + 0.0004, "<b>LH</b>", size=11, color=t.bear_text, xanchor="center", yanchor="bottom")
        k = first_close_below(PIV[29], 34)
        ch.hline(29, k + 0.4, PIV[29], color=t.bear_text, dash="dash")
        ch.callout(k, C[k].c, 33.0, 1.2560, "Close below the last higher low:<br>the uptrend is over",
                   xanchor="center")
    ch.header("Price Action · Trend Analysis", "Trend Analysis — From Strong to Exhausted",
              "GBP/USD · 4-hour candles · shallow pullbacks along a trendline, then a deep one that breaks it",
              key=[("━", t.ink2, "Trendline"), ("━", t.zone, "20 EMA")])
    ch.footnote("Synthetic candles built from the swing points in the Trend Analysis lesson")
    ch.caption()
    ch.axes(x_range=[-0.8, N - 0.2], y_range=[1.2480, 1.2750], y_dtick=0.0040, y_fmt=".4f", x_title="4-hour candles",
            x_ticks=(list(range(0, N, 5)), [str(i + 1) for i in range(0, N, 5)]))
    return ch.fig


def main():
    paths = save(NAME, build, "Trend Strength", OUT)
    print(NAME, [round(depth(*l) * 100) for l in LEGS], first_close_below(PIV[29], 34),
          ', '.join(p.name for p in paths))


if __name__ == "__main__":
    main()
